/**
 * Renders products into a specific carousel track.
 */
function renderCarouselProducts(trackId, filterCriterion) {
    const track = document.getElementById(trackId);
    if (!track || typeof productsDB === 'undefined') return;

    track.innerHTML = '';

    let productList = Object.keys(productsDB).map(id => ({
        id,
        ...productsDB[id]
    }));

    if (typeof filterCriterion === 'string') {
        productList = productList.filter(p => p.collection === filterCriterion);
    } else if (typeof filterCriterion === 'function') {
        productList = productList.filter(filterCriterion);
    }

    let htmlContent = '';
    productList.forEach(p => {
        htmlContent += createProductCardHTML(p);
    });

    track.innerHTML = htmlContent;

    // Check initial arrow state right after rendering
    const container = track.parentElement;
    if (container) {
        updateCarouselArrows(container);
    }
}


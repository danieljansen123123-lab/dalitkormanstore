// 4. הוספה חכמה לעגלה (תומכת בכל סוגי הנתונים ומזהה כמות/שם בצורה מדויקת)
window.addToCart = function(arg1, arg2, arg3, arg4) {
    let id, name, price, img, qtyToAdd = 1;

    if (typeof arg1 === 'object' && arg1 !== null) {
        id = arg1.id || arg1._id || arg1.productId;
        name = arg1.name || arg1.title || arg1.productName;
        price = arg1.price !== undefined ? arg1.price : arg1.cost;
        img = arg1.img || arg1.image || arg1.src;
        if (arg1.quantity) qtyToAdd = Number(arg1.quantity) || 1;
    } else {
        id = arg1;
        // זיהוי אם הפרמטר השני הוא כמות (למשל addToCart('id', 1))
        if (arg2 !== undefined && (!isNaN(Number(arg2)) && (arg3 === undefined || isNaN(Number(arg3))))) {
            qtyToAdd = Number(arg2) || 1;
            name = undefined;
            price = undefined;
            img = undefined;
        } else {
            name = arg2;
            price = arg3;
            img = arg4;
        }
    }

    // השלמת פרטי המוצר מ-productsDB במידה וקיימים
    if (typeof productsDB !== 'undefined' && id && productsDB[id]) {
        const p = productsDB[id];
        if (!name || !isNaN(Number(name))) {
            name = p.name || p.title;
        }
        if (price === undefined || price === null || isNaN(Number(price))) {
            price = p.price;
        }
        if (!img) {
            img = p.img || p.image;
        }
    }

    // אבטחה אחרונה לשם המוצר והמחיר
    if (!name || !isNaN(Number(name))) {
        name = (typeof id === 'string' && isNaN(Number(id))) ? id : 'מוצר קוסמטיקה';
    }
    price = Number(price) || 0;
    img = img || '';

    window.cart = JSON.parse(localStorage.getItem('cart')) || window.cart || [];
    
    const existingIndex = window.cart.findIndex(item => item.id === id);
    if (existingIndex > -1) {
        window.cart[existingIndex].quantity = (Number(window.cart[existingIndex].quantity) || 0) + qtyToAdd;
        window.cart[existingIndex].name = name; // עדכון השם במידה והיה שגוי בעבר
        if (price > 0) window.cart[existingIndex].price = price;
        if (img) window.cart[existingIndex].img = img;
    } else {
        window.cart.push({
            id: id,
            name: name,
            price: price,
            img: img,
            quantity: qtyToAdd
        });
    }

    localStorage.setItem('cart', JSON.stringify(window.cart));
    window.openCart();
};


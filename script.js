function renderReviews() {
    const grid = document.getElementById('reviews-grid');
    if (!grid || !Array.isArray(window.REVIEWS_DATA)) return;

    const filledStar = `<svg viewBox="0 0 24 24" fill="#e5c07b"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>`;
    const emptyStar = `<svg viewBox="0 0 24 24" fill="none" stroke="#e5c07b" stroke-width="1.5"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>`;

    grid.innerHTML = window.REVIEWS_DATA.map(r => {
        const rating = Math.max(0, Math.min(5, Number(r.rating) || 5));
        const stars = Array.from({ length: 5 }, (_, i) => i < rating ? filledStar : emptyStar).join('');
        return `
            <div class="review-card">
                <div class="review-stars">${stars}</div>
                <p class="review-text">${r.text || ''}</p>
                <div class="review-author">${r.name || ''}</div>
            </div>
        `;
    }).join('');

    // Stars animate in (pop/scale) once each card scrolls into view
    const cards = grid.querySelectorAll('.review-card');
    if ('IntersectionObserver' in window) {
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('in-view');
                    observer.unobserve(entry.target);
                }
            });
        }, { threshold: 0.2 });
        cards.forEach(card => observer.observe(card));
    } else {
        cards.forEach(card => card.classList.add('in-view'));
    }
}


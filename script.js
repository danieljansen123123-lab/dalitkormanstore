function renderCart() {
    // 🔒 1. ALWAYS CLEAN MUTATED LOCAL STORAGE FIRST
    const cart = getSanitizedCart();
    window.cart = cart;
    localStorage.setItem('cart', JSON.stringify(cart));

    // 🔒 2. STRICT LIVE SALE CHECK
    const isSaleActive = Boolean(
        window.saleSettings && 
        (window.saleSettings.active === true || window.saleSettings.isActive === true)
    );

    // 🔒 3. CALCULATE FREE ITEMS ONLY IF SALE IS ACTIVE
    let freeCounts = {};
    if (isSaleActive && typeof window.calculateCartDiscounts === 'function') {
        const discountData = window.calculateCartDiscounts(cart);
        freeCounts = discountData.freeCounts || {};
    }

    let html = '';
    let finalTotal = 0;

    cart.forEach((item, index) => {
        const p = (typeof productsDB !== 'undefined' && productsDB[item.id]) ? productsDB[item.id] : item;
        if (!p) return;

        // Base price always comes directly from DB
        const basePrice = Number(p.price || 0);
        const quantity = Number(item.quantity || 1);
        const freeQty = isSaleActive ? (freeCounts[index] || 0) : 0;
        const paidQty = Math.max(0, quantity - freeQty);
        
        const itemTotal = basePrice * paidQty;
        finalTotal += itemTotal;

        // Default: Pure, un-discounted rendering
        let priceDisplayHtml = `<span style="font-weight: bold; color: #000;">₪${itemTotal}</span>`;

        // Sale rendering: ONLY if sale is genuinely active
        if (isSaleActive && freeQty > 0) {
            priceDisplayHtml = `
                <span style="font-weight: bold; color: #e91e63;">₪${itemTotal}</span>
                <s style="color: #999; margin: 0 4px;">₪${basePrice * quantity}</s>
                <span style="color: #e91e63; font-weight: bold;">(${freeQty} בחינם!)</span>
            `;
        }

        html += `
            <div class="cart-item" style="display: flex; align-items: center; justify-content: space-between; border-bottom: 1px solid #eee; padding: 12px 0;">
                <button onclick="removeFromCart(${index})" style="background:none; border:none; cursor:pointer; color:#999; font-size:1.2rem;">&times;</button>
                
                <div style="flex-grow: 1; text-align: right; padding: 0 10px;">
                    <div style="font-weight: bold;">${item.name || p.name}</div>
                    <div style="margin: 4px 0;">${priceDisplayHtml}</div>
                    <div style="display: inline-flex; align-items: center; border: 1px solid #ccc; border-radius: 4px;">
                        <button onclick="updateCartItemQty(${index}, 1)" style="padding: 2px 6px; background:none; border:none; cursor:pointer;">+</button>
                        <span style="padding: 0 8px;">סה"כ ${quantity}</span>
                        <button onclick="updateCartItemQty(${index}, -1)" style="padding: 2px 6px; background:none; border:none; cursor:pointer;">-</button>
                    </div>
                </div>

                <img loading="lazy" src="${item.img || p.img}" style="width: 45px; height: 45px; object-fit: contain;">
            </div>
        `;
    });

    // Update your DOM containers here
    const container = document.getElementById('cart-items-container') || document.querySelector('.cart-items');
    if (container) container.innerHTML = html;
}
function getSanitizedCart() {
    const rawCart = JSON.parse(localStorage.getItem('cart')) || window.cart || [];
    
    return rawCart.filter(item => {
        // Remove standalone gift items added by old sale scripts
        if (item.isGift || item.isFree) return false;
        return true;
    }).map(item => {
        const product = (typeof productsDB !== 'undefined' && productsDB[item.id]) ? productsDB[item.id] : null;
        return {
            ...item,
            // Force price back to official database price (fixes mutated 0 prices)
            price: product ? Number(product.price) : Number(item.price || 0)
        };
    });
}


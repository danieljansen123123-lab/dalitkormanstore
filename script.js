function toggleCardExpand(productId) {
    const targetCard = document.getElementById(`card-${productId}`);
    if (!targetCard) return;

    const isAlreadyExpanded = targetCard.classList.contains('expanded');

    // Close all open cards across the track/grid
    document.querySelectorAll('.product-card.expanded').forEach(card => {
        card.classList.remove('expanded');
    });

    // Expand only the selected card
    if (!isAlreadyExpanded) {
        targetCard.classList.add('expanded');
    }
}

// 3. Add to Cart & Automatically Collapse the Card
// 🎉 אנימציית "נוסף לעגלה!" - הופכת כל כפתור הוספה לעגלה לסימן וי ירוק לרגע, ואז מחזירה אותו למצב המקורי
window.playAddedToCartFeedback = function(buttonEl) {
    if (!buttonEl) return;

    if (!buttonEl.dataset.originalHtml) {
        buttonEl.dataset.originalHtml = buttonEl.innerHTML;
    }

    const checkSvg = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><polyline points="20 6 9 17 4 12"></polyline></svg>`;
    buttonEl.innerHTML = `${checkSvg}<span>נוסף לעגלה!</span>`;
    buttonEl.classList.add('added-feedback-active');

    clearTimeout(buttonEl._addedFeedbackTimeout);
    buttonEl._addedFeedbackTimeout = setTimeout(() => {
        buttonEl.innerHTML = buttonEl.dataset.originalHtml;
        buttonEl.classList.remove('added-feedback-active');
    }, 1600);
};

function handleInCardAddToCart(productId, buttonEl) {
    if (typeof addToCart === 'function') {
        addToCart(productId, 1);
    }

    if (buttonEl) {
        window.playAddedToCartFeedback(buttonEl);
    }

    // Collapse card slightly delayed so the "added" checkmark is actually visible first
    const card = document.getElementById(`card-${productId}`);
    if (card) {
        setTimeout(() => card.classList.remove('expanded'), 900);
    }
}


window.syncSaleUI = function() {
    const isSaleActive = Boolean(
        (window.saleSettings && (window.saleSettings.active || window.saleSettings.isActive)) ||
        localStorage.getItem('isSaleActive') === 'true'
    );

    // Toggle a class on the body element for CSS targeting
    if (isSaleActive) {
        document.body.classList.add('sale-is-active');
        document.body.classList.remove('sale-is-off');
    } else {
        document.body.classList.add('sale-is-off');
        document.body.classList.remove('sale-is-active');
    }
};
window.calculateCart = function(cartItems, liveSaleSettings) {
    // 🔒 Strictly verify sale status directly from DB config
    const isSaleActive = Boolean(liveSaleSettings && liveSaleSettings.active === true);

    let total = 0;
    const processedItems = cartItems.map(item => {
        const basePrice = Number(item.price || 0);
        const qty = Number(item.quantity || 1);

        // Calculate free items ONLY if sale is globally active
        const freeQty = isSaleActive ? Math.floor(qty / 3) : 0; // Example: 2+1 promotion
        const paidQty = qty - freeQty;
        const itemTotal = basePrice * paidQty;

        total += itemTotal;

        return {
            ...item,
            singlePrice: basePrice,
            quantity: qty,
            freeQuantity: freeQty,
            totalItemPrice: itemTotal,
            isSaleActive: isSaleActive
        };
    });

    return {
        items: processedItems,
        grandTotal: total,
        isSaleActive: isSaleActive
    };
};
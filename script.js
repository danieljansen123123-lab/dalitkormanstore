function normalizeForSearch(str) {
    return (str || '').toString().toLowerCase().replace(/[\s\-_]+/g, '');
}

// חיפוש משותף: לפי שם מוצר, מותג (כולל אי-התאמות רווח/מקף), קטגוריה (לפי מילים נרדפות) ותיאור קצר
window.searchProducts = function(query) {
    const q = (query || '').trim().toLowerCase();
    if (!q || typeof productsDB === 'undefined') return [];
    const qNorm = normalizeForSearch(q);

    const matchedCollections = new Set(
        Object.keys(CATEGORY_SEARCH_SYNONYMS).filter(slug =>
            CATEGORY_SEARCH_SYNONYMS[slug].some(term => term.includes(q) || q.includes(term))
        )
    );

    return Object.keys(productsDB)
        .map(id => ({ id, ...productsDB[id] }))
        .filter(p => {
            const nameMatch = (p.name || '').toLowerCase().includes(q);
            const brandMatch = (p.brand || '').toLowerCase().includes(q) || normalizeForSearch(p.brand).includes(qNorm);
            const categoryMatch = matchedCollections.has(p.collection);
            const descMatch = (p.shortDesc || '').toLowerCase().includes(q);
            return nameMatch || brandMatch || categoryMatch || descMatch;
        });
};


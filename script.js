// 2. חישוב מבצעים חכם (מעניק הנחה על המוצרים הזולים ביותר)
window.calculateCartDiscounts = function(cartArray) {
    const currentCart = cartArray || window.cart || [];
    if (!currentCart || currentCart.length === 0) {
        return { finalTotal: 0, freeCounts: {} };
    }

    // 🔒 מקור האמת היחיד לסטטוס מבצע: window.activeShopSales, שנטען מ-Firestore (אוסף Sales, מבצעים עם status === 'active').
    // לעולם לא ממציאים כאן מבצע פעיל בברירת מחדל - אם עדיין לא נטען, פשוט אין מבצעים כרגע (מערך ריק).
    const activeSales = window.activeShopSales || [];

    let flatCart = [];
    currentCart.forEach((item, index) => {
        const p = (typeof productsDB !== 'undefined' && productsDB[item.id]) ? productsDB[item.id] : item;
        const currentPrice = Number(p.price || item.price) || 0;
        const qty = Number(item.quantity) || 1;
        for (let i = 0; i < qty; i++) {
            flatCart.push({ price: currentPrice, index: index });
        }
    });

    flatCart.sort((a, b) => b.price - a.price);

    const plusOneSale = activeSales.find(s => s.type === '1_plus_1');
    const buyXgetY = activeSales.find(s => s.type === 'buy_x_get_y');

    let finalTotal = 0;
    let freeCounts = {};
    const totalItems = flatCart.length;
    let freeItemsCount = 0;

    if (plusOneSale) {
        freeItemsCount = Math.floor(totalItems / 2);
    } else if (buyXgetY) {
        const x = Number(buyXgetY.buyX) || 1;
        const y = Number(buyXgetY.getY) || 1;
        const groupSize = x + y;
        freeItemsCount = Math.floor(totalItems / groupSize) * y;
    }
    // 🔒 אין מבצע 1+1 או "קנה וקבל" פעיל כרגע -> freeItemsCount נשאר 0, כלומר אין הנחה בכלל.
    // (זה בדיוק המקום שבו קודם הייתה ברירת מחדל שגויה של "חצי מהעגלה חינם" גם כשאין שום מבצע פעיל)

    flatCart.forEach((item, i) => {
        if (i >= totalItems - freeItemsCount) {
            freeCounts[item.index] = (freeCounts[item.index] || 0) + 1;
        } else {
            finalTotal += item.price;
        }
    });

    return { finalTotal, freeCounts };
};


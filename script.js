document.addEventListener('DOMContentLoaded', () => {
    const track = document.querySelector('.scroll-track');
    const items = document.querySelectorAll('.clinic-accordion-item');
    const images = document.querySelectorAll('.treatments-img');
    const imageWrapper = document.querySelector('.sticky-image-wrapper');
    const bookingBtn = document.querySelector('.booking-btn-wrapper'); 

    if (!track || items.length === 0) return;

    const DESKTOP_BREAKPOINT = 900;
    let syncingFromClick = false; // avoids the scroll listener fighting a click-triggered scrollTo

    // מעדכן איזה טיפול פעיל ואיזו תמונה מוצגת - פונקציה משותפת לגלילה וללחיצה
    function setActiveTreatment(activeIndex) {
        items.forEach((item, index) => {
            item.classList.toggle('active', index === activeIndex);
        });
        images.forEach((img, index) => {
            img.classList.toggle('active-img', index === activeIndex);
        });
        if (bookingBtn) {
            bookingBtn.classList.toggle('show-btn', activeIndex === items.length - 1);
        }
    }

    // 🔒 לחיצה על כותרת טיפול מפעילה אותו תמיד, בכל גודל מסך - גיבוי אמין.
    // במובייל, קליק גם גולל את רצועת התמונות לתמונה המתאימה.
    items.forEach((item, index) => {
        const header = item.querySelector('.clinic-accordion-header');
        if (!header) return;
        header.addEventListener('click', () => {
            setActiveTreatment(index);
            if (window.innerWidth <= DESKTOP_BREAKPOINT && imageWrapper) {
                syncingFromClick = true;
                imageWrapper.scrollTo({ left: index * imageWrapper.clientWidth, behavior: 'smooth' });
                setTimeout(() => { syncingFromClick = false; }, 500);
            }
        });
    });

    // במובייל: גרירה/החלקה של רצועת התמונות מעדכנת איזה טיפול פתוח,
    // לפי מיקום הגלילה בפועל - חישוב פשוט ואמין, ללא תלות בגובה המסך.
    if (imageWrapper) {
        setupDragToScroll(imageWrapper);

        let scrollDebounce = null;
        imageWrapper.addEventListener('scroll', () => {
            if (window.innerWidth > DESKTOP_BREAKPOINT || syncingFromClick) return;
            clearTimeout(scrollDebounce);
            scrollDebounce = setTimeout(() => {
                const width = imageWrapper.clientWidth;
                if (!width) return;
                const index = Math.round(imageWrapper.scrollLeft / width);
                setActiveTreatment(Math.max(0, Math.min(items.length - 1, index)));
            }, 100);
        });
    }

    // גלילה דביקה (pinned scroll) - דסקטופ בלבד. במובייל האפקט מוחלף
    // לגלריה נגררת (למעלה) כי חישוב לפי גובה מסך לא אמין בדפדפני מובייל
    // (שם שורת הכתובת גדל/מתכווץ תוך כדי גלילה ומזיז את גובה החלון).
    window.addEventListener('scroll', () => {
        if (window.innerWidth <= DESKTOP_BREAKPOINT) return;

        const stickyEl = document.querySelector('.sticky-viewport');
        if (!stickyEl) return;

        const rect = track.getBoundingClientRect();
        const stickyHeight = stickyEl.getBoundingClientRect().height;
        const scrollableDistance = rect.height - stickyHeight;
        if (scrollableDistance <= 0) return;

        const scrolled = -rect.top;
        let progress = scrolled / scrollableDistance;
        progress = Math.max(0, Math.min(1, progress));

        const activeIndex = Math.round(progress * (items.length - 1));
        setActiveTreatment(activeIndex);
    });
});


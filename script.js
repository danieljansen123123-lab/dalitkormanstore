// 1. שאיבת המבצעים בעת טעינת האתר - עם ניסיונות חוזרים כדי לעבוד גם ברשתות
// מובייל אטיות/לא יציבות. הגרסה הקודמת בדקה פעם אחת בלבד אם פיירבייס מוכן
// (אחרי 800ms קבוע) ושלחה שאילתה אחת בלבד ללא ניסיון חוזר - אם אחד מהם
// נכשל (חיבור איטי, ניתוק רגעי), המבצע פשוט לא היה נרשם באותה טעינת עמוד,
// בשקט וללא שום סימן. עכשיו יש בדיקה חוזרת + ניסיון חוזר לשאילתה עצמה.
document.addEventListener('DOMContentLoaded', () => {
    let dbCheckAttempts = 0;
    const MAX_DB_CHECK_ATTEMPTS = 20; // עד כ-6 שניות המתנה לפיירבייס (20 × 300ms)

    function waitForFirebaseAndFetchSales() {
        if (window.db && window.collection && window.getDocs) {
            fetchActiveSales();
            return;
        }
        dbCheckAttempts++;
        if (dbCheckAttempts < MAX_DB_CHECK_ATTEMPTS) {
            setTimeout(waitForFirebaseAndFetchSales, 300);
        } else {
            console.error("Firebase לא נטען בזמן - לא ניתן היה לבדוק מבצעים פעילים בטעינת עמוד זו.");
        }
    }

    async function fetchActiveSales(retriesLeft = 2) {
        try {
            const salesRef = window.collection(window.db, 'Sales');
            const snap = await window.getDocs(salesRef);

            window.activeShopSales = [];
            snap.forEach(doc => {
                const sale = doc.data();
                if (sale.status === 'active') window.activeShopSales.push(sale);
            });

            if (window.activeShopSales.length > 0) {
                // א. הוספת באנר הכרזה
                const announcement = window.activeShopSales[0].announcementTitle;
                if (announcement && !document.getElementById('sale-banner')) {
                    const banner = document.createElement('div');
                    banner.id = 'sale-banner';
                    banner.style.cssText = "background: #e91e63; color: white; text-align: center; padding: 12px; font-weight: bold; font-size: 1rem; letter-spacing: 1px; z-index: 99999; position: relative; animation: fadeInDown 0.5s ease;";
                    banner.innerHTML = `🎉 ${announcement} 🎉`;
                    document.body.insertBefore(banner, document.body.firstChild);
                }

                // ב. עדכון המחירים והתגיות במאגר המוצרים (אחוזי הנחה)
                const percentSales = window.activeShopSales.filter(s => s.type === 'percent');
                if (percentSales.length > 0 && typeof productsDB !== 'undefined') {
                    Object.keys(productsDB).forEach(id => {
                        let p = productsDB[id];
                        for (let sale of percentSales) {
                            let applies = false;
                            if (sale.target === 'storewide') applies = true;
                            else if (sale.target === 'category' && p.collection === sale.targetValue) applies = true;
                            else if (sale.target === 'item' && id === String(sale.targetValue)) applies = true;

                            if (applies) {
                                p.originalPrice = p.price; 
                                p.price = p.price - (p.price * (sale.discount / 100)); 
                                p.saleBadge = `-${sale.discount}%`; 
                                break; 
                            }
                        }
                    });
                }

                // ג. רינדור מחדש של האתר כדי שהשינויים יופיעו מיד
                if (typeof renderAllProducts === 'function') renderAllProducts();
                if (typeof renderFeaturedGrid === 'function') renderFeaturedGrid();
                if (typeof renderCarouselProducts === 'function') {
                    renderCarouselProducts('carousel-track-1', p => p.collection === 'serums');
                    renderCarouselProducts('carousel-track-2', 'cleansers-peels');
                }
                if (typeof updateCartUI === 'function') window.updateCartUI();
            }

            // 🔒 מודיעים לכל דף שמאזין (כמו הקופה) שנתוני המבצעים הגיעו בפועל מפיירבייס,
            // כדי שיוכל לרנדר מחדש את המחיר שלו - גם אם זה קרה אחרי הרינדור הראשוני שלו.
            document.dispatchEvent(new CustomEvent('shopSalesLoaded', { detail: { activeShopSales: window.activeShopSales } }));
        } catch (err) {
            console.error("שגיאה במשיכת מבצעים:", err, "- נותרו ניסיונות:", retriesLeft);
            if (retriesLeft > 0) {
                setTimeout(() => fetchActiveSales(retriesLeft - 1), 1000);
            }
        }
    }

    waitForFirebaseAndFetchSales();
});


/**
 * מפרמטת תאריך לפי הזמן המקומי (YYYY-MM-DD), במקום toISOString() שמשתמש
 * ב-UTC ועלול לתת תאריך שגוי בשעות הלילה המוקדמות בישראל.
 */
window.formatDateLocal = function(dateObj) {
    const y = dateObj.getFullYear();
    const m = String(dateObj.getMonth() + 1).padStart(2, '0');
    const d = String(dateObj.getDate()).padStart(2, '0');
    return `${y}-${m}-${d}`;
};

/**
 * מחזירה רשימת שעות פנויות (מערך מחרוזות "HH:MM") ליום נתון עבור טיפול
 * במשך נתון, בהתחשב בשעות הפעילות ובתורים קיימים (שלא בוטלו) לאותו יום.
 */
window.getAvailableSlotsForDate = async function(dateStr, durationMinutes, excludeAppointmentId) {
    const dateObj = new Date(dateStr + 'T00:00:00');
    const dayOfWeek = dateObj.getDay();
    const hours = BUSINESS_HOURS[dayOfWeek];
    if (!hours) return []; // יום סגור

    const [openH, openM] = hours.open.split(':').map(Number);
    const [closeH, closeM] = hours.close.split(':').map(Number);
    const openMinutes = openH * 60 + openM;
    const closeMinutes = closeH * 60 + closeM;

    let candidateSlots = [];
    for (let m = openMinutes; m + durationMinutes <= closeMinutes; m += APPOINTMENT_SLOT_INTERVAL_MINUTES) {
        candidateSlots.push(m);
    }

    // אם התאריך הוא היום - הסרת שעות שכבר עברו
    const now = new Date();
    if (dateStr === window.formatDateLocal(now)) {
        const nowMinutes = now.getHours() * 60 + now.getMinutes();
        candidateSlots = candidateSlots.filter(m => m > nowMinutes);
    }

    // שליפת תורים קיימים לאותו יום (לא כולל תורים שבוטלו, ולא כולל את התור
    // שעורכים כרגע, אם צוין - כדי שלא "תתפוס" את עצמה) לבדיקת חפיפה
    let existingRanges = [];
    try {
        const q = window.query(
            window.collection(window.db, 'Appointments'),
            window.where('date', '==', dateStr),
            window.where('status', '==', 'confirmed')
        );
        const snap = await window.getDocs(q);
        snap.forEach(docSnap => {
            if (excludeAppointmentId && docSnap.id === excludeAppointmentId) return;
            const d = docSnap.data();
            const [h, mi] = (d.time || '00:00').split(':').map(Number);
            const start = h * 60 + mi;
            existingRanges.push([start, start + (d.durationMinutes || 30)]);
        });
    } catch (err) {
        console.error('שגיאה בבדיקת תורים קיימים:', err);
    }

    const availableSlots = candidateSlots.filter(slotStart => {
        const slotEnd = slotStart + durationMinutes;
        return !existingRanges.some(([exStart, exEnd]) => slotStart < exEnd && slotEnd > exStart);
    });

    return availableSlots.map(m => {
        const h = Math.floor(m / 60);
        const mi = m % 60;
        return `${String(h).padStart(2, '0')}:${String(mi).padStart(2, '0')}`;
    });
};


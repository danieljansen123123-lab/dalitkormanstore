/* ==========================================================================
   Carousel Logic: Hold to Scroll & Arrow Fading
   ========================================================================== */

let holdScrollState = { rafId: null, timeoutId: null, wrapper: null, direction: 0 };

/**
 * Checks scroll position and toggles arrow visibility/fading.
 */
function updateCarouselArrows(wrapper) {
    const parentContainer = wrapper.closest('.carousel-container');
    if (!parentContainer) return;

    const prevArrow = parentContainer.querySelector('.prev-arrow'); // Right arrow
    const nextArrow = parentContainer.querySelector('.next-arrow'); // Left arrow

    const maxScroll = wrapper.scrollWidth - wrapper.clientWidth;
    const currentScroll = wrapper.scrollLeft;

    // RTL handling: standard vs inverted scroll values across browsers
    const isAtBeginning = Math.abs(currentScroll) <= 5;
    const isAtEnd = Math.abs(Math.abs(currentScroll) - maxScroll) <= 5;

    if (prevArrow) {
        if (isAtBeginning) {
            prevArrow.classList.add('arrow-hidden');
        } else {
            prevArrow.classList.remove('arrow-hidden');
        }
    }

    if (nextArrow) {
        if (isAtEnd) {
            nextArrow.classList.add('arrow-hidden');
        } else {
            nextArrow.classList.remove('arrow-hidden');
        }
    }
}

/**
 * Handles smooth horizontal scrolling for carousels (single click/tap).
 */
function moveCarousel(trackId, direction) {
    const track = document.getElementById(trackId);
    if (!track) return;

    const container = track.parentElement;
    const scrollAmount = 266; // Distance per step

    if (container) {
        container.scrollBy({
            left: direction * scrollAmount,
            behavior: 'smooth'
        });
    }
}

/**
 * Starts scrolling when pressing an arrow button: one immediate smooth jump
 * for a normal click, then - only if still held past a short delay - hands
 * off to a continuous requestAnimationFrame glide instead of repeatedly
 * firing new smooth-scrollBy calls (which was interrupting itself every
 * 200ms and causing the visible stutter).
 */
function startHoldScroll(trackId, direction) {
    const track = document.getElementById(trackId);
    if (!track) return;
    const wrapper = track.parentElement;
    if (!wrapper) return;

    stopHoldScroll(); // clear any previous state first

    // Immediate response for a simple click/tap
    wrapper.scrollBy({ left: direction * 266, behavior: 'smooth' });

    holdScrollState.wrapper = wrapper;
    holdScrollState.direction = direction;
    holdScrollState.timeoutId = setTimeout(() => {
        const GLIDE_PIXELS_PER_FRAME = 9;
        function glide() {
            if (!holdScrollState.wrapper) return;
            holdScrollState.wrapper.scrollLeft += holdScrollState.direction * GLIDE_PIXELS_PER_FRAME;
            holdScrollState.rafId = requestAnimationFrame(glide);
        }
        holdScrollState.rafId = requestAnimationFrame(glide);
    }, 350); // only kicks in if still held - a normal click never reaches this
}

/**
 * Stops continuous scrolling when holding stops.
 */
function stopHoldScroll() {
    if (holdScrollState.timeoutId) {
        clearTimeout(holdScrollState.timeoutId);
        holdScrollState.timeoutId = null;
    }
    if (holdScrollState.rafId) {
        cancelAnimationFrame(holdScrollState.rafId);
        holdScrollState.rafId = null;
    }
    holdScrollState.wrapper = null;
}

/**
 * Attach listeners to arrows for scroll monitoring and hold events.
 */
/**
 * Adds click-and-drag scrolling with the mouse (touch devices already scroll
 * natively now that the wrapper uses overflow-x:auto instead of hidden).
 * Also swallows the click that would otherwise fire on a card right after a
 * drag, so dragging past a product doesn't accidentally open/navigate it.
 */
function setupDragToScroll(wrapper) {
    let isDown = false;
    let startX = 0;
    let startScrollLeft = 0;
    let dragged = false;
    let pendingDx = 0;
    let rafId = null;

    function applyPendingScroll() {
        wrapper.scrollLeft = startScrollLeft - pendingDx;
        rafId = null;
    }

    wrapper.addEventListener('mousedown', (e) => {
        isDown = true;
        dragged = false;
        wrapper.classList.add('is-dragging');
        startX = e.pageX;
        startScrollLeft = wrapper.scrollLeft;
    });

    // Stops the browser's native "ghost image" drag on product photos, which
    // otherwise fights with the custom drag gesture and feels jerky.
    wrapper.addEventListener('dragstart', (e) => {
        if (isDown) e.preventDefault();
    });

    window.addEventListener('mousemove', (e) => {
        if (!isDown) return;
        const dx = e.pageX - startX;
        if (Math.abs(dx) > 5) dragged = true;
        pendingDx = dx;
        if (rafId === null) {
            rafId = requestAnimationFrame(applyPendingScroll);
        }
    });

    window.addEventListener('mouseup', () => {
        if (!isDown) return;
        isDown = false;
        wrapper.classList.remove('is-dragging');
    });

    wrapper.addEventListener('mouseleave', () => {
        if (!isDown) return;
        isDown = false;
        wrapper.classList.remove('is-dragging');
    });

    // Capture phase so this runs before a card's own onclick handler
    wrapper.addEventListener('click', (e) => {
        if (dragged) {
            e.preventDefault();
            e.stopPropagation();
        }
    }, true);
}

function setupCarouselEventListeners() {
    document.querySelectorAll('.carousel-container').forEach(container => {
        const wrapper = container.querySelector('.carousel-track-wrapper');
        if (!wrapper) return;

        // Listen for scroll events to update arrow fade states
        wrapper.addEventListener('scroll', () => {
            updateCarouselArrows(wrapper);
        });

        setupDragToScroll(wrapper);

        // Setup hold-to-scroll on buttons
        const prevArrow = container.querySelector('.prev-arrow');
        const nextArrow = container.querySelector('.next-arrow');
        const track = container.querySelector('.carousel-track');

        if (!track) return;
        const trackId = track.id;

        [ { btn: prevArrow, dir: 1 }, { btn: nextArrow, dir: -1 } ].forEach(({ btn, dir }) => {
            if (!btn) return;

            // Mouse events
            btn.addEventListener('mousedown', () => startHoldScroll(trackId, dir));
            btn.addEventListener('mouseup', stopHoldScroll);
            btn.addEventListener('mouseleave', stopHoldScroll);

            // Touch events for mobile/tablets
            btn.addEventListener('touchstart', (e) => {
                e.preventDefault(); // Prevents double triggers on mobile
                startHoldScroll(trackId, dir);
            });
            btn.addEventListener('touchend', stopHoldScroll);
        });

        // Initial check
        updateCarouselArrows(wrapper);
    });
}

/**
 * Wires up the results (before/after) carousel: native touch scroll works
 * automatically now that .results-track-wrapper uses overflow-x:auto, mouse
 * drag reuses the same handler as the product carousels, and the arrow
 * buttons fade out at the start/end just like the product carousel arrows.
 */
function setupResultsCarousel() {
    const wrapper = document.querySelector('.results-track-wrapper');
    if (!wrapper) return;

    setupDragToScroll(wrapper);

    function updateResultsArrows() {
        const container = wrapper.closest('.results-carousel-container');
        if (!container) return;
        const prevArrow = container.querySelector('.prev-results');
        const nextArrow = container.querySelector('.next-results');

        const maxScroll = wrapper.scrollWidth - wrapper.clientWidth;
        const currentScroll = wrapper.scrollLeft;
        const isAtBeginning = Math.abs(currentScroll) <= 5;
        const isAtEnd = Math.abs(Math.abs(currentScroll) - maxScroll) <= 5;

        if (prevArrow) prevArrow.classList.toggle('arrow-hidden', isAtBeginning);
        if (nextArrow) nextArrow.classList.toggle('arrow-hidden', isAtEnd);
    }

    wrapper.addEventListener('scroll', updateResultsArrows);
    updateResultsArrows();
}

